async def captcha_press(ctx, q, cid, uid):
    presser = q.from_user
    if presser.id != uid and not await is_admin(ctx, cid, presser.id):
        return await q.answer(tr(cid, "captcha_not_you"), show_alert=True)
    key = f"{cid}:{uid}"
    p = pend().pop(key, None)
    if p is None:  # انتهت المهلة أو سبق التحقق
        await q.answer()
        return await try_delete(q.message)
    touch()
    try:
        await do_unmute(ctx, cid, uid)
    except Exception as e:
        pend()[key] = p
        log.warning("captcha unmute failed: %s", e)
        return await q.answer(str(e)[:150], show_alert=True)
    await q.answer(tr(cid, "captcha_ok"))
    await try_delete(q.message)
    user = presser if presser.id == uid else (await ctx.bot.get_chat_member(cid, uid)).user
