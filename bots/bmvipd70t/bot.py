async def find_user(ctx, cid, uname):
    """@username -> (id, name). الطرق: ذاكرة البوت (كل من رآه) ثم بحث تيليجرام نفسه."""
    k = uname.lower()
    hit = data.get("users", {}).get(k)
    if hit:
        uid, name = hit
        try:
            mem = await ctx.bot.get_chat_member(cid, uid)
            if (getattr(mem.user, "username", None) or "").lower() == k:
                return uid, mem.user.full_name
            data["users"].pop(k, None)  # المعرّف انتقل لشخص آخر
            touch()
        except Exception:
            return uid, name
    try:  # يعمل إن كان صاحب الحساب قد راسل البوت
        ch = await ctx.bot.get_chat("@" + uname)
        if ch.type == "private":
            name = " ".join(x for x in (ch.first_name, getattr(ch, "last_name", None)) if x) or uname
            data.setdefault("users", {})[k] = [ch.id, name[:40]]
            touch()
            return ch.id, name
    except Exception:
        pass
    return None


async def resolve(update, ctx, reply):
    m, cid = update.effective_message, update.effective_chat.id
    args = list(ctx.args)
    if m.reply_to_message and m.reply_to_message.from_user:
        u = m.reply_to_message.from_user
        return u.id, u.full_name, args
    if args and args[0].isdigit():
        uid = int(args[0])
        return uid, await name_of(ctx, cid, uid), args[1:]
    for e in (m.entities or ()):  # شخص بلا معرّف تم اختياره من القائمة
        if e.type == "text_mention" and getattr(e, "user", None):
            return e.user.id, e.user.full_name, args[1:]
    if args:
        mt = re.fullmatch(r'["“”]?@["“”]?(\w{4,32})["“”]?', args[0])
        if mt:
            found = await find_user(ctx, cid, mt.group(1))
            if found:
                return found[0], found[1], args[1:]
            await reply(tr(cid, "user_nf", u=mt.group(1)))
            return None
    await reply(tr(cid, "need_target"))
    return None


async def mod(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    m, chat, me = update.effective_message, update.effective_chat, update.effective_user
    cid = chat.id
