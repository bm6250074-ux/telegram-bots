def words_summary(cid, entries, bad):
    items = list(entries.items())
    shown = items if len(items) <= 12 else items[:8]
    lst = "\n".join(f"• {w} — {fmt_dur(cid, v) if v else tr(cid, 'w_warnonly')}" for w, v in shown)
