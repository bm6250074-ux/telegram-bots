def _build_periodic():
    themes = []
    for name, ti, si, xt, xs in P_THEMES:
        themes.append((name, [P_TIPS[i] for i in ti] + xt, [P_STEPS[i] for i in si] + xs))
    seqs = []
    for t, (_, tips, steps) in enumerate(themes):
        nT, nS = len(tips), len(steps)
        sh = next(v for v in (3, 5, 7, 11, 13) if v % nS)
        seqs.append([(t, r, (q + r * sh) % nS) for q in range(nS) for r in range(nT)])
    order, pos = [], [0] * len(seqs)
    while True:  # نبدّل بين المواضيع بالتناوب حتى لا تتوالى رسالتان من موضوع واحد
        moved = False
        for t, seq in enumerate(seqs):
            if pos[t] < len(seq):
                order.append(seq[pos[t]])
                pos[t] += 1
                moved = True
        if not moved:
            return themes, order


P_BUILT, P_ORDER = _build_periodic()
PERIODIC_N = len(P_ORDER)   # عدد الرسائل الفريدة قبل أن تبدأ من الأولى


def periodic_text(k):
    """الرسالة رقم k (تبدأ من 0): موضوع + نصيحة + خطوة من الموضوع نفسه + دعوة + أمنية."""
    k %= PERIODIC_N
    t, r, a = P_ORDER[k]
    name, tips, steps = P_BUILT[t]
    return (f"{name}\n{P_TH[k % len(P_TH)]}\n\u201c{tips[r]}\u201d {P_EMO[(k * 5) % len(P_EMO)]}\n"
            f"{P_SH[(k * 3 + r) % len(P_SH)]}\n{steps[a]}\n"
            f"{P_CLOSE[(k * 7 + a) % len(P_CLOSE)]}\n{P_WISH[(k * 11 + r) % len(P_WISH)]}")


